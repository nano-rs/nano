//! NAN-4919: the deploy guard accepts what the compiler renders and refuses
//! anything it would not have produced.
use super::*;
use serde_json::json;

fn step(id: &str, kind: &str, config: Value) -> Step {
    Step {
        id: id.into(),
        name: id.into(),
        kind: kind.into(),
        enabled: true,
        condition: None,
        config: config.as_object().unwrap().clone(),
    }
}

fn pinned() -> BTreeSet<String> {
    native::PINNED_RUNTIME_TRANSFORMS
        .iter()
        .map(|s| s.to_string())
        .collect()
}

fn with_combine_runtime() -> BTreeSet<String> {
    let mut set = pinned();
    set.insert("reduce".into());
    set.insert("lua".into());
    set
}

/// Render a plan the way `parser_config` does: an identity `_parse`, then
/// the generated chain.
fn rendered(plan: &Plan) -> String {
    let chain = native::render(plan, "src", "src_parse").unwrap();
    let mut doc = toml::Table::new();
    let mut parse = toml::Table::new();
    parse.insert("type".into(), "remap".into());
    parse.insert("inputs".into(), toml::Value::Array(vec!["source_router.src".into()]));
    parse.insert("source".into(), ".".into());
    let mut transforms = chain.transforms;
    transforms.insert("src_parse".into(), parse.into());
    doc.insert("transforms".into(), transforms.into());
    toml::to_string(&doc).unwrap()
}

fn full_plan() -> Plan {
    Plan {
        version: 2,
        revision: 3,
        steps: vec![
            step("mask", "mask", json!({"fields":["user"],"operation":"hash"})),
            step("noise", "filter", json!({"predicate":".level == \"debug\"","action":"drop"})),
            step("dedupe", "dedupe", json!({"fields":["message"],"cacheEvents":100})),
            step(
                "route",
                "route",
                json!({"mode":"first","routes":[{"label":"a","predicate":".x == 1"},{"label":"b","predicate":".x == 2","drop":true}]}),
            ),
            step(
                "lookup",
                "lookup",
                json!({"table":"owners","version":"1","rows":[{"host":"h1","owner":"alice"}],"match":{"host":"host"},"outputs":{"owner":"unmapped.owner"}}),
            ),
        ],
    }
}

#[test]
fn generated_pipelines_pass_the_guard() {
    let plan = full_plan();
    let stored = plan.stored().unwrap();
    check_document("src", &stored, &rendered(&plan), &pinned()).unwrap();
}

#[test]
fn combine_needs_reduce_and_lua_in_the_runtime() {
    let mut plan = full_plan();
    plan.steps.push(step("combine", "combine", json!({"keys":["host"],"maxEvents":10})));
    let stored = plan.stored().unwrap();
    let doc = rendered(&plan);
    let refused = check_document("src", &stored, &doc, &pinned()).unwrap_err();
    assert!(refused.contains("reduce and lua"), "{refused}");
    check_document("src", &stored, &doc, &with_combine_runtime()).unwrap();
}

#[test]
fn non_transform_sections_and_foreign_components_are_refused() {
    let plan = full_plan();
    let stored = plan.stored().unwrap();
    let doc = rendered(&plan);
    let sink = format!("{doc}\n[sinks.exfil]\ntype = \"http\"\ninputs = [\"src_parse\"]\n");
    assert!(check_document("src", &stored, &sink, &pinned()).is_err());
    let tables = format!("{doc}\n[enrichment_tables.t]\ntype = \"file\"\n");
    assert!(check_document("src", &stored, &tables, &pinned()).is_err());
    // A `_pipe_` component under a plain VRL parser was not generated by us.
    assert!(check_document("src", ".x = 1", &doc, &pinned()).is_err());
    // Another source's namespace.
    let foreign = doc.replace("src_pipe_2_native", "other_pipe_2_native");
    assert!(check_document("src", &stored, &foreign, &pinned()).is_err());
}

#[test]
fn smuggled_stateful_and_metadata_writing_components_are_refused() {
    let plan = full_plan();
    let stored = plan.stored().unwrap();
    let doc = rendered(&plan);
    let mut parsed: toml::Table = doc.parse().unwrap();
    let transforms = parsed["transforms"].as_table_mut().unwrap();
    // Unbounded dedupe cache.
    let mut evil = transforms.clone();
    evil["src_pipe_2_native"]["cache"]["num_events"] = 10_000_000.into();
    let text = toml::to_string(&toml::Table::from_iter([("transforms".to_string(), evil.into())])).unwrap();
    assert!(check_document("src", &stored, &text, &pinned()).is_err());
    // A generated remap rewritten to forge the input identity.
    let mut evil = transforms.clone();
    evil["src_pipe_4_native"]["source"] = "%nano_credential_id = \"forged\"".into();
    let text = toml::to_string(&toml::Table::from_iter([("transforms".to_string(), evil.into())])).unwrap();
    assert!(check_document("src", &stored, &text, &pinned()).is_err());
    // Enrichment-table calls are never generated.
    let mut evil = transforms.clone();
    evil["src_pipe_4_native"]["source"] =
        "x, err = get_enrichment_table_record(\"t\", {\"a\": \"b\"})".into();
    let text = toml::to_string(&toml::Table::from_iter([("transforms".to_string(), evil.into())])).unwrap();
    assert!(check_document("src", &stored, &text, &pinned()).is_err());
    // A lua transform outside a trusted combine envelope.
    let mut evil = transforms.clone();
    evil.insert(
        "src_pipe_9_bound".into(),
        toml::Value::Table(toml::Table::from_iter([
            ("type".to_string(), "lua".into()),
            ("inputs".to_string(), toml::Value::Array(vec!["src_parse".into()])),
        ])),
    );
    let text = toml::to_string(&toml::Table::from_iter([("transforms".to_string(), evil.into())])).unwrap();
    assert!(check_document("src", &stored, &text, &with_combine_runtime()).is_err());
}

#[test]
fn tampered_combine_envelope_is_refused() {
    let mut plan = full_plan();
    plan.steps.push(step("combine", "combine", json!({"keys":["host"],"maxEvents":10})));
    let stored = plan.stored().unwrap();
    let mut parsed: toml::Table = rendered(&plan).parse().unwrap();
    let transforms = parsed["transforms"].as_table_mut().unwrap();
    let restore = transforms
        .keys()
        .find(|k| k.ends_with("_restore"))
        .unwrap()
        .clone();
    transforms[&restore]["source"] = "%source_type = \"audit\"".into();
    let text = toml::to_string(&parsed).unwrap();
    assert!(check_document("src", &stored, &text, &with_combine_runtime()).is_err());
}

#[test]
fn invalid_or_edited_plans_are_refused_before_deploy() {
    let stored = full_plan().stored().unwrap();
    let edited = stored.replace(BODY, ". = {}");
    assert!(check_document("src", &edited, "", &pinned()).is_err());
}

/// Codex P1 (NAN-4919): the deploy guard compiles a plan's `_parse` and every
/// owned remap with metadata read-only, so a forged identity write is refused
/// whatever its spelling.
#[test]
fn deploy_guard_refuses_two_target_metadata_writes() {
    let plan = full_plan();
    let stored = plan.stored().unwrap();
    let mut parsed: toml::Table = rendered(&plan).parse().unwrap();
    let transforms = parsed["transforms"].as_table_mut().unwrap();
    for name in ["src_pipe_4_native", "src_parse"] {
        let mut evil = transforms.clone();
        evil[name]["source"] = "%nano_credential_id, err = to_string(.spoof)\n.".into();
        let text = toml::to_string(&toml::Table::from_iter([(
            "transforms".to_string(),
            evil.into(),
        )]))
        .unwrap();
        let refused = check_document("src", &stored, &text, &pinned()).unwrap_err();
        assert!(refused.contains("read-only"), "{name}: {refused}");
    }
}

#[test]
fn advanced_vrl_cannot_write_metadata() {
    for code in [
        "%nano_credential_id = \"x\"",
        "%source_type=\"x\"",
        "del(%nano_credential_name)",
        // Codex P1 (NAN-4919): the two-target form a text pattern missed.
        "%nano_credential_id, err = to_string(.spoof)",
        "%nano_credential_id,err=to_string(.spoof)",
        "% = {}",
    ] {
        assert!(refuse_metadata_writes(code).is_err(), "{code}");
        assert!(compile_step(&step("v", "vrl", json!({ "code": code }))).is_err(), "{code}");
    }
    for code in [
        ".input = %nano_credential_id",
        "if %source_type == \"x\" { .a = 1 }",
        ".ok = %source_type != \"y\"",
    ] {
        refuse_metadata_writes(code).unwrap();
    }
}
