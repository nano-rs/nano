/// NAN-3460: platform logons / logoffs / account changes are OCSF
/// Authentication 3002 and Account Change 3001. zero-nan3460 is
/// zero-nan3339-v2 with ONLY the current audit lane (it admits the IAM
/// classes); through its bronze row contract sink admission lands them
/// beside every API Activity row. zero-nan3339-v2 — the base live tenants
/// carry — refuses them at the lane, which is why zero-nan3460 must roll
/// before the control plane writes IAM rows.
#[test]
fn the_nan3460_base_lands_authentication_and_account_change() {
    let at = chrono::DateTime::parse_from_rfc3339("2026-10-09T18:19:53.538Z")
        .unwrap()
        .with_timezone(&chrono::Utc);
    let user = Uuid::new_v4();
    let iam = |name: &'static str, event: AuditEvent, class: i64| {
        let id = event.event_id();
        let line = event.to_ocsf_event_for_lake_with(at, id, TENANT, true);
        assert_eq!(line["class_uid"], class, "{name}");
        (name, id, line.to_string(), false)
    };
    let mut lines = lines();
    let iam_lines = vec![
        iam(
            "login, known client",
            AuditEvent::builder(AuditSource::Auth, "login_success")
                .actor(Some(user), Some("dan@nano.rs".to_string()))
                .resource("user", Some(user), Some("dan@nano.rs".to_string()))
                .client(Some("198.51.100.23".to_string()), Some("Mozilla/5.0".to_string()))
                .build(),
            3002,
        ),
        iam(
            "logout, actor id only, no client",
            AuditEvent::builder(AuditSource::Auth, "logout").actor(Some(user), None).resource("session", None, None).build(),
            3002,
        ),
        iam(
            "failed login by name",
            AuditEvent::builder(AuditSource::Auth, "login_failed")
                .actor(None, Some("probe@example.com".to_string()))
                .client(Some("203.0.113.9".to_string()), None)
                .success(false)
                .build(),
            3002,
        ),
        iam(
            "user disabled by an administrator",
            AuditEvent::builder(AuditSource::Settings, "user_disabled")
                .actor(Some(Uuid::new_v4()), Some("admin@nano.rs".to_string()))
                .resource("user", Some(user), Some("dan@nano.rs".to_string()))
                .client(Some("10.1.2.3".to_string()), None)
                .build(),
            3001,
        ),
    ];
    lines.extend(iam_lines.iter().cloned());
    let base = module_base("selected-parser-zero-nan3460.js");
    let (admitted, refused, first) = admit(&base, &lines);
    assert_eq!(refused, 0, "{first}");
    let want: BTreeSet<String> = lines.iter().map(|(_, id, _, _)| id.to_string()).collect();
    assert_eq!(admitted, want);

    // Exactly the lane upgrade of zero-nan3339-v2.
    let previous = module_base("selected-parser-zero-nan3339-v2.js");
    let derived = platform_audit_lane::upgrade_platform_audit_lane(&previous).unwrap();
    assert_eq!(archive::pack(&derived).unwrap(), archive::pack(&base).unwrap());

    // The live base refuses every IAM line at its lane (6003 only).
    for (name, _, line, _) in &iam_lines {
        assert!(platform_audit_lane::lake_row(&previous, line, TENANT).is_err(), "{name}");
    }
}

/// NAN-3460 rollout gate: with `NANO_AUDIT_OCSF_IAM_CLASSES` off (the
/// default r21 ships with), every action the IAM table would reclassify is
/// still API Activity 6003, and the bases live tenants carry today
/// (zero-nan3304-v2, zero-nan3339-v2) land every such row — so the API can
/// roll before any Worker carries zero-nan3460. Same lines land on
/// zero-nan3460 too.
#[test]
fn flag_off_rows_land_on_the_live_bases() {
    use nanosiem_core::audit::ocsf_mapping::IAM_ACTIONS;
    let at = chrono::DateTime::parse_from_rfc3339("2026-10-09T18:19:53.538Z")
        .unwrap()
        .with_timezone(&chrono::Utc);
    let mut lines = Vec::new();
    for (action, _) in IAM_ACTIONS {
        let user = Uuid::new_v4();
        for (shape, event) in [
            (
                "named, user resource, client",
                AuditEvent::builder(AuditSource::Auth, action)
                    .actor(Some(user), Some("dan@nano.rs".to_string()))
                    .resource("user", Some(user), Some("dan@nano.rs".to_string()))
                    .client(Some("198.51.100.23".to_string()), Some("Mozilla/5.0".to_string()))
                    .build(),
            ),
            ("actor id only, no client", AuditEvent::builder(AuditSource::Auth, action).actor(Some(user), None).build()),
            (
                "failed by name, type-only resource",
                AuditEvent::builder(AuditSource::Auth, action)
                    .actor(None, Some("probe@example.com".to_string()))
                    .resource("session", None, None)
                    .success(false)
                    .build(),
            ),
        ] {
            let id = event.event_id();
            let line = event.to_ocsf_event_for_lake_with(at, id, TENANT, false);
            assert_eq!(line["class_uid"], 6003, "{action} / {shape}");
            assert!(line.get("unmapped").map_or(true, |u| u.get("action").is_none()), "{action} / {shape}");
            lines.push((*action, id, line.to_string(), false));
        }
    }
    let want: BTreeSet<String> = lines.iter().map(|(_, id, _, _)| id.to_string()).collect();
    for base in ["selected-parser-zero-nan3304-v2.js", "selected-parser-zero-nan3339-v2.js", "selected-parser-zero-nan3460.js",
        "selected-parser-zero-nan3523.js"] {
        let (admitted, refused, first) = admit(&module_base(base), &lines);
        assert_eq!(refused, 0, "{base}: {first}");
        assert_eq!(admitted, want, "{base}");
    }
}
