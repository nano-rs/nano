//! NAN-3304 (second hop): platform audit rows whose client or actor is
//! unknown are refused by `ingest[T]` after the Worker acked them.
//!
//! The control plane's OCSF mirror (`AuditEvent::to_ocsf_event_for_lake`)
//! says "unknown" with nulls: `src_endpoint: {"ip": null}`, and for a system
//! or session-only actor `actor.user: {"name": null, "uid": null}`. Bronze is
//! Parquet, which carries no nulls, so `ingest[T]` validates `{}` and refuses
//! the row ("src_endpoint: at least one of [ip, uid, name, ...] is required").
//! Live on the load-test tenant (base zero-nan3304, bundle r8), 2026-10-08 18:20:27Z and
//! 18:30:05Z: `bronze data refused` / `admission_invalid` for 3 of the 4 audit
//! rows delivered after the base roll. Replaying the tenant's 3300 backfill
//! rows through the live base admits 1522 and refuses 1778 (1777 null-only
//! `src_endpoint` / `actor.user`, 1 type-only `resources[0]`); the fixed base
//! admits all 3300.
//!
//! Every hop after the delivery line is production code: the release base's
//! own audit lane and lake-sink prepare (`platform_audit_lane::lake_row`), a
//! Parquet object as the bronze sink writes it, and the real salvaging
//! admission `lake_part_ingest` runs.

