"""Generate the operator's Helm values for nano Self-run on Kubernetes.

Writes two files on the operator's workstation:
  <out>/values-site.yaml     non-secret: URLs, hostnames, pull secret, TLS issuer,
                             schema, retention, ClickHouse storage/replicas. Reviewable.
  <out>/values-licence.yaml  SECRET (mode 0600): licence URL, deployment id, licence token,
                             read from the app.nano.rs enrollment file. Never commit or print it.

  helm show values oci://us-central1-docker.pkg.dev/nano-rs/nanosiem-customer/charts/nano --version <chart-version> > chart-values.yaml
  helm-values.py --chart-values chart-values.yaml --enrollment ~/nano-enrollment.env \
     --base-url https://nano.example.com --app-host nano.example.com --ingest-host ingest.nano.example.com \
     --pull-secret nano-registry --issuer letsencrypt --storage-gi 600 --hot-days 365 --out ./nano-deploy-work/helm

The chart's own presets (values-small/standard/large/xlarge.yaml) carry the sizing;
pass the preset size.py chose to helm separately. --chart-values lets the script use
the deployment-id key that this chart version understands.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys


def read_enrollment(path: str) -> dict:
    want = {}
    with open(os.path.expanduser(path), encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, v = line.split("=", 1)
            v = v.strip().strip("'\"")
            if k in ("LICENSE_URL", "LICENSE_TOKEN", "NANO_DEPLOYMENT_ID") and v:
                want[k] = v
    missing = {"LICENSE_URL", "LICENSE_TOKEN", "NANO_DEPLOYMENT_ID"} - set(want)
    if missing:
        raise SystemExit(f"enrollment file lacks {', '.join(sorted(missing))}")
    return want


def top_level_deployment_id(chart_values: str) -> bool:
    """True when the chart has nano.deploymentId (2.0.1+); False for the 2.0.0 shape."""
    in_nano = False
    for line in open(chart_values, encoding="utf-8"):
        if re.match(r"^nano:\s*$", line):
            in_nano = True
            continue
        if in_nano and re.match(r"^\S", line):
            return False
        if in_nano and re.match(r"^  deploymentId:", line):
            return True
    return False


def y(value) -> str:
    return json.dumps(value)  # JSON scalars are valid YAML


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--chart-values", required=True, help="output of `helm show values` for the chart version")
    ap.add_argument("--enrollment", help="app.nano.rs enrollment file (omit to install unlicensed)")
    ap.add_argument("--base-url", required=True)
    ap.add_argument("--app-host", required=True)
    ap.add_argument("--ingest-host", required=True)
    ap.add_argument("--pull-secret", default="nano-registry")
    ap.add_argument("--issuer", help="cert-manager ClusterIssuer name (omit when TLS comes from the cloud or a Secret)")
    ap.add_argument("--storage-gi", type=int)
    ap.add_argument("--storage-class")
    ap.add_argument("--replicas", type=int, choices=[1, 2], default=1, help="2 = ClickHouse HA (~2x cost, Keeper x3)")
    ap.add_argument("--hot-days", type=int)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    if a.app_host == a.ingest_host:
        raise SystemExit("--app-host and --ingest-host must differ")
    os.makedirs(a.out, mode=0o700, exist_ok=True)

    site = ["# nano Self-run site values (non-secret). Generated by nano-deploy helm-values.py.",
            "nano:", f"  baseUrl: {y(a.base_url)}", "  schemaProfile: ocsf"]
    if a.hot_days:
        site += ["  retention:", f"    hotDays: {a.hot_days}"]
    site += ["global:", f"  imagePullSecrets: [{y(a.pull_secret)}]",
             "ingress:", f"  host: {y(a.app_host)}",
             "ingest:", f"  hostname: {y(a.ingest_host)}"]
    if a.issuer:
        site += ["tls:", "  certManager:", f"    issuerRef: {{kind: ClusterIssuer, name: {y(a.issuer)}}}"]
    ch = []
    if a.storage_gi or a.storage_class:
        ch.append("  storage:")
        if a.storage_gi:
            ch.append(f"    size: {a.storage_gi}Gi")
        if a.storage_class:
            ch.append(f"    storageClass: {y(a.storage_class)}")
    if a.replicas == 2:
        ch += ["  replicas: 2", "  keeper:", "    replicas: 3"]
    if ch:
        site += ["clickhouse:"] + ch
    with open(os.path.join(a.out, "values-site.yaml"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(site) + "\n")
    print(f"wrote {a.out}/values-site.yaml")

    if a.enrollment:
        e = read_enrollment(a.enrollment)
        lic = ["# SECRET: nano licence values. Mode 0600. Never commit, print or paste this file.",
               "nano:", "  license:", f"    url: {y(e['LICENSE_URL'])}"]
        if top_level_deployment_id(a.chart_values):
            lic.append(f"  deploymentId: {y(e['NANO_DEPLOYMENT_ID'])}")
        else:
            lic += ["  extraEnv:", "    - name: NANO_DEPLOYMENT_ID", f"      value: {y(e['NANO_DEPLOYMENT_ID'])}"]
        lic += ["secrets:", f"  licenseToken: {y(e['LICENSE_TOKEN'])}"]
        path = os.path.join(a.out, "values-licence.yaml")
        fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write("\n".join(lic) + "\n")
        os.chmod(path, 0o600)
        print(f"wrote {path} (mode 0600; contents not shown)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
