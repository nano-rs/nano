-- Name: lookup_ioc(text, public.ioc_type); Type: FUNCTION; Schema: public; Owner: -
--

CREATE OR REPLACE FUNCTION public.lookup_ioc(p_value text, p_type public.ioc_type DEFAULT NULL::public.ioc_type) RETURNS TABLE(source_id text, ioc_value text, ioc_type public.ioc_type, threat_type text, malware text, confidence_level integer, first_seen_at timestamp with time zone, last_seen_at timestamp with time zone, tags text[])
    LANGUAGE plpgsql
    AS $$
BEGIN
    -- Handle NULL or empty value
    IF p_value IS NULL OR p_value = '' THEN
        RETURN;
    END IF;

    RETURN QUERY
    SELECT
        ie.source_id,
        ie.ioc_value,
        ie.ioc_type,
        ie.threat_type,
        ie.malware,
        ie.confidence_level,
        ie.first_seen_at,
        ie.last_seen_at,
        ie.tags
    FROM ioc_enrichments ie
    JOIN enrichment_sources es ON ie.source_id = es.id
    WHERE ie.ioc_value = lower(p_value)
      AND (p_type IS NULL OR ie.ioc_type = p_type)
      AND es.enabled = true
      AND ie.expires_at > NOW()
    ORDER BY ie.confidence_level DESC NULLS LAST
    LIMIT 1;
END;
$$;


--
-- Name: lookup_iocs_bulk(text[]); Type: FUNCTION; Schema: public; Owner: -
--

CREATE OR REPLACE FUNCTION public.lookup_iocs_bulk(p_values text[]) RETURNS TABLE(lookup_value text, source_id text, ioc_type public.ioc_type, threat_type text, malware text, confidence_level integer, tags text[])
    LANGUAGE plpgsql
    AS $$
BEGIN
    RETURN QUERY
    SELECT DISTINCT ON (v.val)
        v.val as lookup_value,
        ie.source_id,
        ie.ioc_type,
        ie.threat_type,
        ie.malware,
        ie.confidence_level,
        ie.tags
    FROM unnest(p_values) AS v(val)
    LEFT JOIN ioc_enrichments ie ON ie.ioc_value = lower(v.val)
    LEFT JOIN enrichment_sources es ON ie.source_id = es.id
    WHERE (ie.id IS NULL) OR (es.enabled = true AND ie.expires_at > NOW())
    ORDER BY v.val, ie.confidence_level DESC NULLS LAST;
END;
$$;


