--
-- Name: swap_enrichment_staging(text); Type: FUNCTION; Schema: public; Owner: -
--

CREATE OR REPLACE FUNCTION public.swap_enrichment_staging(p_source_id text) RETURNS bigint
    LANGUAGE plpgsql
    AS $$
DECLARE
    v_count BIGINT;
BEGIN
    -- Get count from staging
    SELECT COUNT(*) INTO v_count FROM ip_enrichments_staging WHERE source_id = p_source_id;

    -- Delete old data for this source from production
    DELETE FROM ip_enrichments WHERE source_id = p_source_id;

    -- Move data from staging to production, deduplicating by (source_id, network)
    -- to prevent unique constraint violations from concurrent staging inserts
    INSERT INTO ip_enrichments (source_id, network, country, country_code, continent, continent_code, asn, as_name, as_domain, extra, created_at)
    SELECT DISTINCT ON (source_id, network)
           source_id, network, country, country_code, continent, continent_code, asn, as_name, as_domain, extra, created_at
    FROM ip_enrichments_staging
    WHERE source_id = p_source_id
    ORDER BY source_id, network, created_at DESC;

    -- Clear staging table for this source
    DELETE FROM ip_enrichments_staging WHERE source_id = p_source_id;

    RETURN v_count;
END;
$$;


--
-- Name: swap_ioc_enrichment_staging(text); Type: FUNCTION; Schema: public; Owner: -
--

CREATE OR REPLACE FUNCTION public.swap_ioc_enrichment_staging(p_source_id text) RETURNS bigint
    LANGUAGE plpgsql
    AS $$
DECLARE
    v_count BIGINT;
BEGIN
    -- Delete old data for this source from production
    DELETE FROM ioc_enrichments WHERE source_id = p_source_id;

    -- Move data from staging to production (deduplicate, keeping highest confidence)
    INSERT INTO ioc_enrichments (
        source_id, ioc_value, ioc_type, original_value,
        threat_type, threat_type_desc, malware, malware_alias, malware_printable,
        confidence_level, first_seen_at, last_seen_at, expires_at,
        tags, reference_url, reporter, extra, created_at
    )
    SELECT DISTINCT ON (source_id, ioc_type, ioc_value)
        source_id, ioc_value, ioc_type, original_value,
        threat_type, threat_type_desc, malware, malware_alias, malware_printable,
        confidence_level, first_seen_at, last_seen_at, expires_at,
        tags, reference_url, reporter, extra, created_at
    FROM ioc_enrichments_staging
    WHERE source_id = p_source_id
    ORDER BY source_id, ioc_type, ioc_value, confidence_level DESC;

    -- Get actual inserted count (after deduplication)
    GET DIAGNOSTICS v_count = ROW_COUNT;

    -- Clear staging table for this source
    DELETE FROM ioc_enrichments_staging WHERE source_id = p_source_id;

    -- Update the enrichment source record count with actual deduplicated count
    UPDATE enrichment_sources
    SET record_count = v_count,
        updated_at = NOW()
    WHERE id = p_source_id;

    RETURN v_count;
END;
$$;


